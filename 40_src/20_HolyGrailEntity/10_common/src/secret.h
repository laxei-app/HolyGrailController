#ifndef _SECRET_H_
#define _SECRET_H_
// カメラのパスワードなど、ファイルに平文で置きたくない値の暗号化。
//
// 【何から守れて、何から守れないか】鍵は固定でコードに埋め込む(ユーザー指定)。したがって
//  **アプリのバイナリを持っている相手には復号できる**。守れるのは「保存ファイルや撮影計画の
//  JSON を覗いただけでパスワードが読めてしまう」ことまで。そこを承知で使うこと。
//  本気で守るなら鍵を端末ごとに作って安全な場所(Android Keystore 等)へ置く必要があるが、
//  エッジ(M5Stack)には置き場所が無く、計画JSONで運ぶ以上どのみち両端で同じ鍵が要る。
//
// 【なぜ自前実装か】エッジは mbedTLS を持っているがスマホのネイティブには無く、JNI で
//  Java の暗号を呼ぶと**エッジとスマホで別実装**になる。同じ値を両端で復号する必要があるので、
//  実装は1つに保つ。ChaCha20 はテーブルも依存も無く、この用途には十分。
//
// 【保存形式】"v1:" + hex(nonce 8byte + 暗号文)。JSON にそのまま入る ASCII のみ。
//  nonce を毎回変えるので、同じパスワードでも保存されるたびに違う文字列になる。
#include <string>

namespace secret
{
	// 平文 → 保存形式。空文字は空文字のまま返す(未設定を暗号化しない)。
	std::string encrypt(const std::string& plain);

	// 保存形式 → 平文。**"v1:" で始まらない文字列はそのまま返す**。
	//  手で書き換えた設定ファイルや、暗号化を入れる前のデータを読めなくしないため。
	std::string decrypt(const std::string& stored);

	// この文字列は暗号化済みか("v1:" で始まるか)。
	bool isEncrypted(const std::string& s);
}

#endif // _SECRET_H_

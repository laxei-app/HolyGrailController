#pragma once
// 「この IP の相手はもう居ない」を、待たずに知るための置き場(2026-08-28)。
//
// 【なぜ要るか】エッジが SoftAP のとき、カメラが電源を切ると Wi-Fi の離脱イベントが
//  **その瞬間に**届く(ARDUINO_EVENT_WIFI_AP_STADISCONNECTED)。ところが撮影ループは
//  それを知らず、TCP のタイムアウトだけで気づこうとしていた。実測(Stick01, 2026-08-28):
//
//    13:47:22 APSTA leave        ← エッジは既に知っている
//    13:47:42 actShutter 失敗(9秒)
//    13:48:06 測光 失敗(24秒)
//    …3コマ繰り返して 13:49:19、さらに再探索を回して ✖ は 13:49:45 以降
//
//  カメラが抜けてから ✖ まで約2分25秒。1コマ36秒(シャッター12秒+測光24秒)が3回、
//  すべて「返事が返らないのを待つ」時間だった。イベントは最初から出ている。
//
// 【使い方】離脱イベントを受けた側が note(ip) を呼ぶ。撮影ループは成功したコマの直後に
//  generation(ip) を控えておき、値が変わっていたら「その IP はもう居ない」と判断する。
//  時刻ではなく世代番号で比べるのは、時計が無い/ずれる端末でも壊れないようにするため。
//
// STA モードでは誰も note を呼ばないので、この仕組みは黙って何もしない。
#include <string>

namespace linkDown
{
	// その IP の相手が居なくなった。何度呼んでもよい(そのたび世代が進む)。
	void note(const std::string& ip);

	// その IP の世代番号。note のたびに増える。まだ一度も抜けていなければ 0。
	unsigned generation(const std::string& ip);
}

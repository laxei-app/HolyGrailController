#ifndef _NOTICE_H_
#define _NOTICE_H_

// ユーザーへ伝える「状態のお知らせ」をコードで表す(2026-08-19)。
//
// 【なぜコードか(ユーザー指示)】表示する文言は UI が持つ。Entity の内部と通信路には
//  コードだけを流す。理由は3つ:
//   ・文言の変更や言い換えで Entity と通信仕様を触らなくて済む
//   ・表示先ごとに出し分けられる(スマホは1文、エッジのLCDは数文字、といった違いを吸収できる)
//   ・将来の多言語化がUI側の差し替えだけで済む
//
// 【付随する数値 n1】「残り何枚」のように数を添えたいものがある。意味はコードごとに決める
//  (下のコメントに書く)。使わないコードでは 0 を流す。UI は自分が知っているコードだけを
//  文章にし、知らないコードは無視してよい(古いUIに新しいコードが届いても壊れない)。
namespace hgc
{
	enum class notice : int
	{
		none              = 0,

		// --- 記録メディア ---
		cardCannotWrite   = 10,	// カードへ記録できない(満杯/異常)。n1=未使用
		cardMissing       = 11,	// カードが入っていない。n1=未使用
		cardReadOnly      = 12,	// 書き込み禁止になっている。n1=未使用
		cardLow           = 13,	// 残りが少ない。n1=あと何枚撮れるかの目安

		// --- カメラ本体 ---
		cameraBatteryLow  = 20,	// カメラの電池が少ない。n1=未使用
		cameraTempWarning = 21,	// 高温の警告(まだ撮れる)。n1=未使用
		cameraTempStopped = 22,	// 高温で撮影できない状態。n1=未使用

		// --- 復帰 ---
		recovered         = 30,	// 直前のお知らせの原因が解消した。n1=解消したコード
	};
}

#endif // _NOTICE_H_

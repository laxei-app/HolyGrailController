#ifndef _NOTICE_H_
#define _NOTICE_H_

// ユーザーへ伝える「状態のお知らせ」をコードで表す(2026-08-19)。
//
// 【なぜコードか(ユーザー指示)】表示する文言は UI が持つ。Entity の内部と通信路には
//  コードだけを流す。理由は3つ:
//   ・文言の変更や言い換えで Entity と通信仕様を触らなくて済む
//   ・表示先ごとに出し分けられる(スマホは1文、エッジのLCDは数文字、といった違いを吸収できる)
//   ・将来の多言語化がUI側の差し替えだけで済む
//
// 【付随する数値 n1】「残り何枚」のように数を添えたいものがある。意味はコードごとに決める
//  (下のコメントに書く)。使わないコードでは 0 を流す。UI は自分が知っているコードだけを
//  文章にし、知らないコードは無視してよい(古いUIに新しいコードが届いても壊れない)。
namespace hgc
{
	enum class notice : int
	{
		none              = 0,

		// --- 記録メディア ---
		cardCannotWrite   = 10,	// カードへ記録できない(満杯/異常)。n1=未使用
		cardMissing       = 11,	// カードが入っていない。n1=未使用
		cardReadOnly      = 12,	// 書き込み禁止になっている。n1=未使用
		cardLow           = 13,	// 残りが少ない。n1=あと何枚撮れるかの目安

		// --- カメラ本体 ---
		cameraBatteryLow  = 20,	// カメラの電池が少ない。n1=未使用
		cameraTempWarning = 21,	// 高温の警告(まだ撮れる)。n1=未使用
		cameraTempStopped = 22,	// 高温で撮影できない状態。n1=未使用

		// --- エッジ端末そのもの ---
		edgeStorageFail   = 40,	// エッジが計画やログを保存できない(SDカード未挿入/書けない)。n1=未使用

		// --- 復帰 ---
		recovered         = 30,	// 直前のお知らせの原因が解消した。n1=解消したコード

		// --- 撮影セッション(2026-08-22。Entity から日本語を無くすため文言をUIへ移した) ---
		captureRecovered    = 50,	// 止まっていたカメラの撮影が戻った。n1=未使用
		captureNotRecording = 51,	// シャッターは通るのに画像が記録されない(オフライン扱いにする)。n1=未使用
		captureLinkLost     = 52,	// 撮影中に接続が切れた(中止まで再接続を続ける)。n1=未使用
		standbyLinkLost     = 53,	// 待機中に接続断を検知して先回り再接続した。n1=未使用
		firstExposureFailed = 54,	// 1枚目の露出をカメラへ適用できなかった。n1=試した回数
		convergeFailed      = 55,	// 撮影開始前の露出合わせに失敗した。内訳はログ(CONV/ERR)。n1=未使用
		cameraBusy          = 60,	// そのカメラは別の撮影で使用中。n1=未使用
		// 同期撮影で指定した台数が、その端末で扱える上限を超えた(2026-08-26)。
		//  上限は端末側の事情(APモードは内部RAMの余裕が少ない)で決まるので、
		//  判定も上限値も**端末側が持つ**。UI は n1 をそのまま文章に埋めればよい。
		//  n1=その端末で扱える台数(主カメラを含む合計)
		syncShotTooMany     = 61,
		// 同期撮影は単独実行。時間が重なる他の撮影があるので開始できない。n1=未使用
		syncShotRunsAlone   = 62,

		// カメラが認証を拒否している(403 Not access)。叩き直しても回復しないので、
		//  カメラ本体の接続設定を入れ直してもらうしかない。資格情報の登録漏れが引き金になる。
		//  n1=未使用
		cameraRefused       = 63,

		// カメラは見つかっているが認証で弾かれた(401)。「見つかりません」と区別して伝える。
		//  記述子(認証不要)は読めているので、居ることは分かっている。n1=未使用
		authMissing         = 64,	// 資格情報が1つも登録されていない
		authWrong           = 65,	// 登録された資格情報では通らなかった
	};
}

#endif // _NOTICE_H_

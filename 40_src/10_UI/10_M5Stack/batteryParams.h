#ifndef _BATTERY_PARAMS_H_
#define _BATTERY_PARAMS_H_
// M5Stack CoreS3 のバッテリ実測値。18_M5Common/batteryLevel.h から参照される。
// 機種ごとに容量も消費電流も違うので、しきい値・ヒステリシスはこのファイルで持つ
// (共通ロジック側には機種名を出さない)。

namespace batt
{
	struct params
	{
		int mvFull;		// これ以上 = 3/3
		int mvMid;		// これ以上 = 2/3
		int mvLow;		// これ以上 = 1/3 (下回ると点滅)
		int mvOff;		// これを下回り続けたら電源断
		int hystMv;		// 復帰(上がる向き)に必要な上乗せ[mV]
		int offConfirm;	// 電源断は連続でこの回数下回ったら実行(BATT判定は60秒間隔)
	};

	// 2026-07-24 実測(USB非接続で電池切れまで): 4073mV → 3041mV / 95分。
	//  点滅10分を除く85分を3等分(28.4分)して「残り時間」から逆算:
	//    残り66.8分 → 3894mV   残り38.4分 → 3770mV   残り10.0分 → 3463mV
	//  この値での検証(実測ログを流したシミュレーション):
	//    3/3=29分 2/3=29分 1/3=28分 点滅=7分、戻りの往復0回(ちらつき無し)
	//
	//  mvOff=3300: 下回ってから電池が尽きるまで実測で約2分しかない。
	//   offConfirm=3(2分)では間に合わないので2回。1回だと瞬間的な電圧降下で誤判定しうる。
	//   これ以上下げると断の判定が間に合わない(実測 3150mV では電源断に到達しなかった)。
	//  hystMv=100: この機体は 100mV で戻りの往復が0回。
	//
	//  2026-07-25 変更: 点滅(mvLow)を 3463→3600 に引き上げ、点滅時間を延長。
	//   実放置で点滅=約7分(アイドル)と短く、撮影中は消費が増えさらに短くなるため。
	//   点滅帯 3300〜3600(300mV)。副作用で 1/3 帯(mvLow〜mvMid=3600〜3770)は短くなる。
	//   ※撮影負荷での段の均等化は撮影中の実測後に4値を割り直す。今回は点滅(mvLow)のみ調整。
	constexpr params kParams { 3894, 3770, 3600, 3300, 100, 2 };
}

#endif // _BATTERY_PARAMS_H_

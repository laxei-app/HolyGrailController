#ifndef _BATTERY_PARAMS_H_
#define _BATTERY_PARAMS_H_
// M5StickS3 のバッテリ実測値。18_M5Common/batteryLevel.h から参照される。
// 機種ごとに容量も消費電流も違うので、しきい値・ヒステリシスはこのファイルで持つ
// (共通ロジック側には機種名を出さない)。

namespace batt
{
	struct params
	{
		int mvFull;		// これ以上 = 3/3
		int mvMid;		// これ以上 = 2/3
		int mvLow;		// これ以上 = 1/3 (下回ると点滅)
		int mvOff;		// これを下回り続けたら電源断
		int hystMv;		// 復帰(上がる向き)に必要な上乗せ[mV]
		int offConfirm;	// 電源断は連続でこの回数下回ったら実行(BATT判定は60秒間隔)
	};

	// 2026-07-24 実測(USB非接続で電池切れまで): 4060mV → 3044mV / 89分。
	//  点滅10分を除く79分を3等分(26.4分)して「残り時間」から逆算:
	//    残り62.7分 → 3856mV   残り36.4分 → 3652mV   残り10.0分 → 3366mV
	//  この値での検証(実測ログを流したシミュレーション):
	//    3/3=27分 2/3=27分 1/3=27分 点滅=6分、戻りの往復0回(ちらつき無し)
	//
	//  mvOff=3300: CoreS3 と同じ理由(下回ってから尽きるまで約2分)。offConfirm=2。
	//  hystMv=120: この機体は 100mV だと 3858→3962→3830mV と揺れて level4→5 へ1回戻った。
	//   120mV にすると戻りの往復が0回になる。**CoreS3(100mV)と違う値なのはこのため。**
	//
	//  2026-07-25 変更: 点滅(mvLow)を 3366→3500 に引き上げ、点滅時間を延長。
	//   実放置で点滅=約3分(アイドル)と特に短く(点滅帯が 66mV しか無かった)、撮影中は
	//   さらに短くなるため。点滅帯 3300〜3500(200mV)。1/3 帯(3500〜3652)は短くなる。
	//   ※撮影負荷での段の均等化は撮影中の実測後に4値を割り直す。今回は点滅(mvLow)のみ調整。
	constexpr params kParams { 3856, 3652, 3500, 3300, 120, 2 };
}

#endif // _BATTERY_PARAMS_H_
